class FakePipResult:
    returncode = 0
    stderr = ""


# A resolved lock the way `uv pip compile --generate-hashes` writes one.
FAKE_LOCK = (
    "# autogenerated by uv\n"
    "strands-agents==1.47.0 \\\n"
    "    --hash=sha256:" + "a" * 64 + "\n"
    "aws-opentelemetry-distro==0.19.0 \\\n"
    "    --hash=sha256:" + "b" * 64 + "\n"
)


def fake_pip_ok(cmd, **kwargs):
    """Stands in for both subprocesses build_zip drives: the uv resolve (writes a
    lock at `-o`) and the pip install (populates `-t`)."""
    fake_pip_ok.last_env = kwargs.get("env")
    if "compile" in cmd:
        Path(cmd[cmd.index("-o") + 1]).write_text(FAKE_LOCK, encoding="utf-8")
        fake_pip_ok.compile_cmd = cmd
        return FakePipResult()
    target = Path(cmd[cmd.index("-t") + 1])
    (target / "strands").mkdir(parents=True, exist_ok=True)
    (target / "strands" / "__init__.py").write_text("")
    (target / "aws_opentelemetry_distro").mkdir(exist_ok=True)
    (target / "aws_opentelemetry_distro" / "__init__.py").write_text("")
    fake_pip_ok.last_cmd = cmd
    return FakePipResult()


def test_build_zip_contains_expected_files(tmp_path: Path):
    zip_path = build_zip(
        "print('agent')",
        ["strands-agents[otel]>=1.0,<2", "aws-opentelemetry-distro>=0.10,<1"],
        tmp_path / "build",
        pip_runner=fake_pip_ok,
    )
    names = zipfile.ZipFile(zip_path).namelist()
    assert "main.py" in names
    assert "requirements.txt" in names
    # the lock ships inside the artifact, so what ran carries what it was built from
    assert "requirements.lock" in names
    assert any(n.startswith("strands/") for n in names)
    assert any(n.startswith("aws_opentelemetry_distro/") for n in names)
    # ARM64 reproducibility flags
    cmd = fake_pip_ok.last_cmd
    assert "--platform" in cmd and "manylinux2014_aarch64" in cmd
    assert "--only-binary=:all:" in cmd
    # the install must verify against the lock, not re-resolve the declared ranges
    assert "--require-hashes" in cmd
    assert "-r" in cmd


