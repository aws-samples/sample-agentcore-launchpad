"""Reference coverage of the ACTUAL evaluation targets a dataset produces (SE-047 B).

One pure helper shared by plan validation, materialization of an *existing* evaluator
reference and the run preflight, so the same question is answered the same way
everywhere: *for this evaluator's level and the ground-truth fields it reads, does every
target it will be applied to carry that reference?*

Targets follow the runner's grouping: a scenario is one session whose turns are its
traces; the scenario-level ``assertions`` / ``expectedTrajectory`` attach to that
session and every ``expectedResponse`` to its turn.

Evaluator needs come from real configuration, never from a plan kind: judge placeholders
(``{expected_response}`` / ``{assertions}`` / ``{expected_tool_trajectory}``), the base
of a derived evaluator, the canonical trajectory builtins, or the declarative rules of a
managed code evaluator. An external code evaluator's needs are unknown and reported so.

A simulated persona scenario (``actor_profile``) has no predefined turns: its traces are
generated by the actor model at run time, so no per-turn ``expected_response`` can ever
exist for them. Such a scenario yields ONE explicit trace target carrying only the
session-scoped references the metadata composer really sends (``assertions`` /
``expected_trajectory``) — a TRACE evaluator that reads ``expected_response`` reports a
gap there instead of passing vacuously on an empty turn list.
"""

from __future__ import annotations

import functools
import re
from typing import Any

from botocore.loaders import Loader
from botocore.model import ServiceModel, Shape
from botocore.validate import ParamValidator

from app.evaluation.agentcore_eval import (
    ALL_BUILTIN_EVALUATORS,
    TRAJECTORY_EVALUATORS,
    ground_truth_placeholders,
)
from app.evaluation.scenarios import normalize_scenarios

FIELDS = ("expected_response", "assertions", "expected_tool_trajectory")
KNOWN_BUILTINS: dict[str, str] = {**ALL_BUILTIN_EVALUATORS, **TRAJECTORY_EVALUATORS}
CONFIG_KINDS = ("llmAsAJudge", "derived", "codeBased")
LEVELS = ("TRACE", "TOOL_CALL", "SESSION")
SIMULATED_TURNS = "simulated turns"
SIMULATED_NOTE = ("persona turns are generated by the actor model at run time and carry no "
                  "predefined reference")


def reference_targets(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Every session and trace target of the dataset with the reference fields it
    carries: ``{"id", "kind": "session"|"trace", "scenario_id", "fields": set}``."""
    out: list[dict[str, Any]] = []
    for scenario in normalize_scenarios(items):
        sid = str(scenario.get("scenario_id") or "")
        turns = scenario.get("turns") or []
        session_fields = set()
        if scenario.get("assertions"):
            session_fields.add("assertions")
        if scenario.get("expected_trajectory"):
            session_fields.add("expected_tool_trajectory")
        if "actor_profile" in scenario:
            out.append({"id": sid, "kind": "session", "scenario_id": sid,
                        "fields": set(session_fields)})
            out.append({"id": f"{sid}/{SIMULATED_TURNS}", "kind": "trace", "scenario_id": sid,
                        "fields": set(session_fields), "simulated": True})
            continue
        responses = [bool((t or {}).get("expected_response")) for t in turns]
        fields = set(session_fields)
        if responses and all(responses):
            fields.add("expected_response")
        out.append({"id": sid, "kind": "session", "scenario_id": sid, "fields": fields})
        for i, has in enumerate(responses):
            t_fields = set(session_fields) | ({"expected_response"} if has else set())
            out.append({"id": f"{sid}/turn {i + 1}", "kind": "trace", "scenario_id": sid,
                        "fields": t_fields})
    return out


def coverage_gaps(items: list[dict[str, Any]], needs: set[str], level: str) -> list[str]:
    """Target ids that lack a reference the evaluator reads. SESSION-level evaluators are
    applied to every session; TRACE/TOOL_CALL evaluators to every trace (a trace also
    sees its session's scoped references). Empty ``needs`` → no gaps."""
    if not needs:
        return []
    kind = "session" if level == "SESSION" else "trace"
    gaps: list[str] = []
    for target in reference_targets(items):
        if target["kind"] != kind:
            continue
        missing = sorted(set(needs) - target["fields"])
        if missing:
            note = f" ({SIMULATED_NOTE})" if target.get("simulated") else ""
            gaps.append(f"{target['id']} lacks {'/'.join(missing)}{note}")
    return gaps


def _service_model() -> ServiceModel:
    """The INSTALLED bedrock-agentcore-control model (a local botocore data file — no
    client, no network). Evidence for shapes, unions, required members and constraints."""
    return ServiceModel(Loader().load_service_model("bedrock-agentcore-control", "service-2"),
                        service_name="bedrock-agentcore-control")


@functools.lru_cache(maxsize=1)
def _config_shape() -> Shape:
    return _service_model().shape_for("EvaluatorConfig")


_NUMBER_TYPES = ("integer", "long", "float", "double")


def _shape_problems(value: Any, shape: Shape, path: str) -> list[str]:
    """Walk ``value`` against ``shape`` and report every completeness / type / constraint
    violation the installed model states: unknown members, missing required members,
    tagged unions with anything but exactly ONE non-empty branch, wrong scalar types (a
    bool is never a number), ``min``/``max`` ranges and string ``pattern``s. A required
    string must be non-blank; a document-typed member accepts any JSON value."""
    if shape.type_name == "structure":
        if shape.metadata.get("document"):
            return []
        if not isinstance(value, dict):
            return [f"{path} is not an object"]
        unknown = sorted(set(value) - set(shape.members))
        problems = [f"{path} carries unknown members {unknown}"] if unknown else []
        if shape.metadata.get("union"):
            present = [k for k in shape.members if k in value]
            if len(present) != 1:
                return problems + [f"{path} must carry exactly one of "
                                   f"{' / '.join(shape.members)}"]
            if value[present[0]] in (None, {}, []):
                return problems + [f"{path}.{present[0]} definition is empty"]
        for name in shape.required_members:
            if name not in value or value[name] is None:
                problems.append(f"{path}.{name} missing")
            elif shape.members[name].type_name == "string" and (
                    not isinstance(value[name], str) or not value[name].strip()):
                problems.append(f"{path}.{name} must be a non-blank string")
        for name, member in shape.members.items():
            if name in value and value[name] is not None:
                problems.extend(_shape_problems(value[name], member, f"{path}.{name}"))
        return problems
    if shape.type_name == "list":
        if not isinstance(value, list):
            return [f"{path} is not a list"]
        problems = _range_problems(len(value), shape, f"{path} length")
        for i, entry in enumerate(value):
            if entry is None:
                problems.append(f"{path}[{i}] is null")
            else:
                problems.extend(_shape_problems(entry, shape.member, f"{path}[{i}]"))
        return problems
    if shape.type_name == "map":
        if not isinstance(value, dict):
            return [f"{path} is not a map"]
        problems = []
        for k, v in value.items():
            problems.extend(_shape_problems(k, shape.key, f"{path} key {k!r}"))
            problems.extend(_shape_problems(v, shape.value, f"{path}[{k!r}]"))
        return problems
    if shape.type_name == "string":
        if not isinstance(value, str):
            return [f"{path} is not a string"]
        problems = _range_problems(len(value), shape, f"{path} length")
        pattern = shape.metadata.get("pattern")
        if pattern and not re.fullmatch(pattern, value):
            problems.append(f"{path} does not match the required pattern")
        return problems
    if shape.type_name in _NUMBER_TYPES:
        if isinstance(value, bool) or not isinstance(value, int | float):
            return [f"{path} is not a number"]
        if shape.type_name in ("integer", "long") and not isinstance(value, int):
            return [f"{path} is not an integer"]
        return _range_problems(value, shape, path)
    if shape.type_name == "boolean":
        return [] if isinstance(value, bool) else [f"{path} is not a boolean"]
    return []


def _range_problems(number: float, shape: Shape, path: str) -> list[str]:
    lo, hi = shape.metadata.get("min"), shape.metadata.get("max")
    if lo is not None and number < lo:
        return [f"{path} is below the minimum {lo}"]
    if hi is not None and number > hi:
        return [f"{path} is above the maximum {hi}"]
    return []


def validate_evaluator_config(config: Any) -> str | None:
    """Exactly ONE complete supported definition, checked member by member against the
    INSTALLED control-plane model (``EvaluatorConfig`` and every nested shape: the
    ``RatingScale`` / ``EvaluatorModelConfig`` / ``CodeBasedEvaluatorConfig`` unions, the
    required ``definition``/``value``/``label`` of every scale entry, ``modelId`` on
    BOTH model branches, typed inference options, the Lambda ARN pattern and the 1–300 s
    timeout). Unknown members anywhere fail; documented optional provider fields
    (``inferenceConfig``, document-typed ``additionalModelRequestFields``, Responses
    ``reasoning`` …) pass. Returns the first problem, or None."""
    if not isinstance(config, dict):
        return "evaluatorConfig is not an object"
    kinds = [k for k in config if k in CONFIG_KINDS]
    unknown = sorted(set(config) - set(CONFIG_KINDS))
    if unknown:
        return f"evaluatorConfig carries unknown members {unknown}"
    if len(kinds) != 1:
        return "evaluatorConfig must carry exactly one of llmAsAJudge / derived / codeBased"
    kind, body = kinds[0], config[kinds[0]]
    if not isinstance(body, dict) or not body:
        return f"{kind} definition is empty"
    shape = _config_shape()
    problems = _shape_problems(config, shape, "evaluatorConfig")
    if problems:
        return problems[0]
    # a rating scale with no entries defines nothing to score against
    if kind == "llmAsAJudge":
        scale = body["ratingScale"]
        branch = next(k for k in scale if k in ("numerical", "categorical"))
        if not scale[branch]:
            return f"evaluatorConfig.llmAsAJudge.ratingScale.{branch} has no entries"
    # botocore's own request validation as a second, independent witness
    report = ParamValidator().validate(config, shape)
    if report.has_errors():
        return report.generate_report().splitlines()[0]
    return None


def builtin_needs(evaluator_id: str) -> set[str]:
    return {"expected_tool_trajectory"} if evaluator_id in TRAJECTORY_EVALUATORS else set()


def needs_from_config(detail: dict[str, Any], managed_rules: list[dict[str, Any]] | None
                      ) -> tuple[set[str] | None, str]:
    """(needs, kind) from a GetEvaluator record. ``None`` needs = unknown (an external code
    evaluator whose rules this platform does not own)."""
    config = detail.get("evaluatorConfig") or {}
    if "llmAsAJudge" in config:
        judge = config.get("llmAsAJudge") or {}
        return set(ground_truth_placeholders(str(judge.get("instructions") or ""))), "judge"
    if "derived" in config:
        derived = config.get("derived") or {}
        return set(builtin_needs(str(derived.get("baseEvaluatorId") or ""))), "derived"
    if managed_rules is None:
        return None, "code"
    needs: set[str] = set()
    for c in managed_rules:
        if c.get("type") == "reference_trajectory":
            needs.add("expected_tool_trajectory")
        if c.get("type") == "reference_response":
            needs.add("expected_response")
    return needs, "code"
