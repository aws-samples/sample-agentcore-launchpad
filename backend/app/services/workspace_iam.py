"""The three service roles a workspace needs, provisioned with boto3.

`launchpad-base` (CDK) creates these for the hub; a console-registered workspace
lives in another region where no stack is deployed, so the bootstrap job has to
create them itself. The statements below are **transcribed from
`infra/stacks/base_stack.py`** and keep the CDK sids, so the two can be diffed
statement by statement during review — the same discipline `agent_iam.py`
follows for per-agent roles.

Deliberate differences from the CDK role (a workspace has no demo layer):

* the gateway role's `hr_lambda.grant_invoke` and `InvokeRestTargets`
  (`execute-api:Invoke` on the office-facts API) statements are absent — those
  targets are CDK-shipped sample *code*, which a boto3 bootstrap does not
  deploy. Nothing else references them.
* names always carry the region. The CDK keeps the original us-west-2 names bare
  (`regional_role_name`), and this module reproduces that rule so a workspace can
  never resolve to a differently-named role than the stack in the same region.

Roles are account-global, so `ensure_role` **refuses an untagged role of the
right name** instead of adopting it: the name may belong to an independent
Launchpad deployment in that region (a CDK stack, or the separate production
install in the same account), and adopting it would silently entangle two
environments.
"""

import json
from collections.abc import Callable
from typing import Any

WORKSPACE_TAG_KEY = "launchpad:workspace"

# Regions whose role names predate multi-region support keep the bare name; see
# infra/stacks/base_stack.py::regional_role_name (kept in sync by hand — the
# backend cannot import the CDK app).
LEGACY_REGION = "us-west-2"

EXECUTION_ROLE_BASE = "launchpad-agent-execution-role"
GATEWAY_ROLE_BASE = "launchpad-gateway-role"
KB_ROLE_BASE = "launchpad-kb-role"
CODEBUILD_ROLE_BASE = "launchpad-codebuild-role"


def regional_role_name(base_name: str, region: str) -> str:
    """Role name for `region`; IAM role names are account-global, not regional."""
    return base_name if region == LEGACY_REGION else f"{base_name}-{region}"


def service_trust_policy(
    service: str, account_id: str, *, source_account: bool = True
) -> dict[str, Any]:
    """Trust policy verbatim from the CDK: the service principal, restricted to
    resources in this account (`aws:SourceAccount`).

    `source_account=False` is for the CodeBuild role, whose CDK counterpart is
    generated by the `codebuild.Project` construct with an unconditioned
    `codebuild.amazonaws.com` trust — a condition the construct does not set is
    one this role must not invent, because a build that cannot assume its role
    fails at package time, not at bootstrap time.
    """
    statement: dict[str, Any] = {
        "Effect": "Allow",
        "Principal": {"Service": service},
        "Action": "sts:AssumeRole",
    }
    if source_account:
        statement["Condition"] = {"StringEquals": {"aws:SourceAccount": account_id}}
    return {"Version": "2012-10-17", "Statement": [statement]}


