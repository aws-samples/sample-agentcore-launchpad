class ForeignResourceError(RuntimeError):
    """A resource of the right name exists but was not made for this workspace."""


def _is_already_exists(exc: Exception) -> bool:
    # Same shape as agent_iam._is_already_exists: botocore's exception classes are
    # generated per client, so there is no importable type to catch.
    return "EntityAlreadyExists" in f"{type(exc).__name__}{exc}"


def _tags(iam: Any, role_name: str) -> dict[str, str]:
    return {
        str(tag.get("Key")): str(tag.get("Value"))
        for tag in iam.list_role_tags(RoleName=role_name).get("Tags", [])
    }


def ensure_role(
    iam: Any,
    *,
    workspace_id: str,
    role_name: str,
    trust_policy: dict[str, Any],
    inline_policies: dict[str, dict[str, Any]],
    description: str,
    log: Callable[[str], None] = lambda _m: None,
) -> str:
    """Create or reconcile one workspace service role; return its ARN.

    Idempotent by name, because the bootstrap job resumes and re-enters stages.
    An existing role is adopted **only** when it carries the
    `launchpad:workspace` tag — an untagged one of the same name belongs to a
    deployment this job did not make (the CDK stack, or another install in the
    same account), and adopting it would hand two environments one role. A tag
    naming a different workspace is adopted and re-stamped: only one workspace
    can exist per (account, region), so the previous owner is gone.
    """
    try:
        created = iam.create_role(
            RoleName=role_name,
            AssumeRolePolicyDocument=json.dumps(trust_policy),
            Description=description,
            Tags=[
                {"Key": WORKSPACE_TAG_KEY, "Value": workspace_id},
                {"Key": "launchpad:managed", "Value": "true"},
            ],
        )
        role_arn = created["Role"]["Arn"]
        log(f"created role {role_name}")
    except Exception as exc:  # noqa: BLE001 — the SDK's typed error is client-specific
        if not _is_already_exists(exc):
            raise
        tags = _tags(iam, role_name)
        owner = tags.get(WORKSPACE_TAG_KEY)
        if owner is None:
            raise ForeignResourceError(
                f"IAM role {role_name} already exists without a "
                f"{WORKSPACE_TAG_KEY} tag — it belongs to another Launchpad "
                "deployment (the launchpad-base CDK stack, or a separate install "
                "in this account). Register this workspace in a region that does "
                "not already host one, or remove the role first."
            ) from exc
        role_arn = iam.get_role(RoleName=role_name)["Role"]["Arn"]
        if owner != workspace_id:
            iam.tag_role(
                RoleName=role_name,
                Tags=[{"Key": WORKSPACE_TAG_KEY, "Value": workspace_id}],
            )
            log(f"adopted role {role_name} from retired workspace '{owner}'")
        else:
            log(f"reusing role {role_name}")
        # Adopting: refresh the trust policy so a tightened condition still lands.
        iam.update_assume_role_policy(
            RoleName=role_name, PolicyDocument=json.dumps(trust_policy)
        )

    for policy_name, document in inline_policies.items():
        iam.put_role_policy(
            RoleName=role_name,
            PolicyName=policy_name,
            PolicyDocument=json.dumps(document),
        )
    return role_arn
