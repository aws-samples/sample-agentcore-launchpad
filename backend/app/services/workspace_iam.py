def regional_role_name(base_name: str, region: str) -> str:
    """Role name for `region`; IAM role names are account-global, not regional.
    N11: `Settings.env_name` is appended last (`...-<region>-<env>`), the same order the
    CDK uses (`suffixed(regional_role_name(...))`), so hub and workspace never disagree."""
    return resource_name(base_name if region == LEGACY_REGION else f"{base_name}-{region}")


def _arn(
    region: str, account_id: str, service: str, resource: str, *, wildcard_region: bool = False
) -> str:
    partition = aws_clients.partition_for_region(region)
    reg = "*" if wildcard_region else region
    return f"arn:{partition}:{service}:{reg}:{account_id}:{resource}"


def _global_arn(region: str, service: str, resource: str) -> str:
    """Region- and account-less ARNs (S3 buckets)."""
    return f"arn:{aws_clients.partition_for_region(region)}:{service}:::{resource}"


def service_trust_policy(
    service: str, account_id: str, *, source_account: bool = True
) -> dict[str, Any]:
    """Trust policy verbatim from the CDK: the service principal, restricted to
    resources in this account (`aws:SourceAccount`).

    `source_account=False` is for the CodeBuild role, whose CDK counterpart is
    generated by the `codebuild.Project` construct with an unconditioned
    `codebuild.<dns-suffix>` trust — a condition the construct does not set is
    one this role must not invent, because a build that cannot assume its role
    fails at package time, not at bootstrap time.
    """
    statement: dict[str, Any] = {
        "Effect": "Allow",
        "Principal": {"Service": service},
        "Action": "sts:AssumeRole",
    }
    if source_account:
        statement["Condition"] = {"StringEquals": {"aws:SourceAccount": account_id}}
    return {"Version": "2012-10-17", "Statement": [statement]}


