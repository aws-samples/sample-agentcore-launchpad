def _pending_force_reauth(agent: Agent, user_id: str | None) -> list[str]:
    """as_user Connections whose revocation is still in force for this user on
    this agent, limited to the spec's own as_user tools. Read per invoke — the
    spec gate keeps it free for every agent without an as_user tool."""
    if not user_id:
        return []
    connections = as_user_connections_stored(agent.spec)
    if not connections:
        return []
    from app.core.db import SessionLocal

    db = SessionLocal()
    try:
        return oauth_sessions.pending_revocations(
            db,
            agent.workspace_id,
            user_id=user_id,
            agent_id=agent.id,
            providers=connections,
        )
    finally:
        db.close()


def _record_auth_sessions(
    agent: Agent,
    user_id: str | None,
    asks: list[dict[str, Any]],
    *,
    console_user: bool = True,
) -> list[dict[str, Any]]:
    """Persist each forwarded 3LO ask against the user it was asked of, and
    strip the session uri from what goes out to the caller.

    The binding leg (CompleteResourceTokenAuth) needs BOTH the session uri and
    the user id; the user id stays server-side (see services/oauth_sessions.py).
    The browser receives the session uri anyway — the IdP redirect carries it to
    the return page — so only the pairing is worth keeping out of the event.

    ``console_user=False`` (the public /v1 API) refuses every ask the same way:
    the consent is completed by the console's return page for the console user
    the ask was recorded against, and a /v1 caller is an API key whose
    ``actor_id`` names nobody who can sign in — so its session could never
    complete (``oauth_sessions.AS_USER_REQUIRES_CONSOLE``). The vault user a
    /v1 turn presents is its scoped actor (``<agent>__<actor_id>``), never a
    console username, so a consent given in Chat does not carry over either:
    as_user tools are a Chat-console feature, and /v1 says so by name instead
    of handing out a consent URL that dead-ends.
    """
    if not asks:
        return asks
    if not console_user:
        first = asks[0]
        raise oauth_sessions.as_user_requires_console(
            provider=str(first.get("provider") or ""),
            tool=str(first.get("tool") or ""),
            agent_id=agent.id,
        )
    from app.core.db import SessionLocal

    out: list[dict[str, Any]] = []
    db = SessionLocal()
    try:
        for ask in asks:
            session_uri = str(ask.get("session_uri") or "")
            if session_uri and user_id:
                oauth_sessions.record_pending(
                    db,
                    agent.workspace_id,
                    session_uri=session_uri,
                    provider=str(ask.get("provider") or ""),
                    user_id=user_id,
                    agent_id=agent.id,
                    tool=str(ask.get("tool") or ""),
                    scopes=ask.get("scopes") or (),
                )
            public = {k: v for k, v in ask.items() if k != "session_uri"}
            out.append({**public, "agent_id": agent.id})
    finally:
        db.close()
    return out


def _agent_workspace(
    agent: Agent, workspace: WorkspaceContext | None
) -> WorkspaceContext:
    """Where this agent's runtime lives.

    The agent row is authoritative, not the caller: both entrances (console chat
    and `/v1`) must reach the same account/region for the same agent. Callers that
    already resolved the workspace pass it, which also keeps the hot path free of
    an extra ledger read per turn.
    """
    return workspace if workspace is not None else context_for_workspace(agent.workspace_id)


def _routing_kwargs(agent: Agent, session_id: str) -> dict[str, Any]:
    """N12 canary routing (plan §B.7): the one hook both entrances share.

    When the ``optimization`` feature is on and a canary owns this
    agent's traffic, ``routing.route_for`` returns the session's sticky arm (writing the
    ``experiment_assignments`` row on first sight) and the invoke call carries it:

    * canary arm → ``qualifier=stable<id6>|treat<id6>`` (Runtime named endpoint) + the
      SDK's experiment baggage keys (owner id + arm, so spans attribute per arm).

    The session id MUST already be resolved by the caller: stickiness hashes it, and
    the row written here is what the verdict later joins ``eval_results`` against.
    One indexed read per invoke when no owner is active.
    """
    if "optimization" not in get_settings().features:
        return {}
    from app.core.db import SessionLocal
    from app.optimization import routing

    db = SessionLocal()
    try:
        route = routing.route_for(db, agent.id, session_id)
    finally:
        db.close()
    if route is None:
        return {}
    kwargs: dict[str, Any] = {"baggage": route.baggage, "launchpad_meta": route.launchpad_meta}
    if route.qualifier:
        kwargs["qualifier"] = route.qualifier
    return kwargs


def runtime_stream_error(exc: rt.SdkStreamError) -> AppError:
    """N17-obs95: the Runtime stream ended on the AgentCore SDK's terminal error frame (or the
    one-body ``{"error": …}`` refusal, a malformed frame, a structured REJECTED body) on a SYNC
    entrance — ``/v1/agents/{id}/invoke`` and the console ``POST /api/agents/{id}/invoke`` —
    where there is no stream to carry an ``error`` event. The same failure Chat renders as its
    terminal ``error`` event becomes the 502 envelope ``agent.runtime_error``: the bounded,
    secret-redacted frame text as the message and the frame's structured ``detail``
    (``{error_type, error, message}``, each value bounded and redacted) — never a bare 500."""
    detail = {
        key: rt.redact_secret_pairs(value) if isinstance(value, str) else value
        for key, value in exc.detail.items()
    }
    return AppError(
        "agent.runtime_error",
        rt.redact_secret_pairs(rt.bounded_error_text(str(exc))),
        detail or None,
        status_code=502,
    )


def _audit_runtime_decision(
    agent: Agent, principal: Principal | None, data: dict[str, Any], *, session_id: str | None,
) -> dict[str, Any]:
    """The `policy_denied` / `policy_decision` frame with its hub audit row id
    (``policy_enforcement.record_runtime_decision``; None when the module is inactive or
    the ledger write failed — the frame still flows)."""
    decision_id = policy_enforcement.record_runtime_decision(
        agent, principal, data, session_id=session_id,
    )
    stamped = {**data, "decision_id": decision_id}
    # A6 (additive): the denying policy's name and the engine stage for the console's card
    return {**stamped, **policy_enforcement.describe_denial(agent, stamped)}


def _gateway_denial(
    agent: Agent, principal: Principal | None, data: dict[str, Any], session_id: str | None,
) -> dict[str, Any] | None:
    """N17-obs507: the `policy_denied` frame derived from a `tool_result` frame that carries
    the Gateway interceptor's denial text (policy names resolved), stamped like a runtime
    frame (`source: "gateway"` ⇒ no hub audit row — the gateway line is the system of
    record); None when the result is not a denial."""
    frame = policy_enforcement.gateway_denial_from_tool_result(agent, data)
    if frame is None:
        return None
    stamped = _audit_runtime_decision(agent, principal, frame, session_id=session_id)
    # describe_denial knows one name; keep the full map the derivation resolved
    stamped["policy_name"] = frame.get("policy_name") or stamped.get("policy_name")
    stamped["policy_names"] = frame.get("policy_names") or {}
    return stamped


# the I1 ``ch`` of a turn by who asks, when the entrance does not name it (stream A2)
_TOKEN_CHANNEL_BY_KIND = {"user": "chat", "api_key": "v1"}


def _token_channel(principal: Principal | None, channel: str | None) -> str:
    if channel:
        return channel
    return _TOKEN_CHANNEL_BY_KIND.get(principal.kind if principal else "", "system")


def _with_principal(kwargs: dict[str, Any], token: str | None) -> None:
    """The token rides in ``payload["launchpad"]`` beside the canary routing pointer (I2)."""
    if token:
        kwargs["launchpad_meta"] = {**(kwargs.get("launchpad_meta") or {}), "principal": token}


def invoke_agent_text(
    agent: Agent,
    prompt: str,
    session_id: str | None = None,
    actor_id: str = "default",
    runtime_user_id: str | None = None,
    workspace: WorkspaceContext | None = None,
    attachments: PreparedAttachments | None = None,
    console_user: bool = True,
    principal: Principal | None = None,
    token_channel: str | None = None,
) -> dict[str, Any]:
    """One synchronous turn. ``console_user=False`` marks a caller with no
    signed-in console user (public /v1): an as_user consent ask is then refused
    by name instead of recorded (see ``_record_auth_sessions``).

    ``principal`` (D20 P1-b, additive) is who is asking — the console ``Identity``
    (``Principal.from_identity``) from Chat, the ``ApiKey`` row from ``/v1``; an internal
    caller passes none and is ``System::"hub"``; it names the principal whose token the
    turn carries to the Gateway (per-user policy) — invoking an agent is NOT a policy
    decision (Global parity ruling 2026-10-27: policies govern Gateway tool calls only)."""
    require_invoke_capability(agent)
    refuse_reserved_session_id(session_id)
    refuse_assistant_session(agent, session_id)
    require_session_open(agent, session_id)
    workspace = _agent_workspace(agent, workspace)
    if attachments:
        prompt = attachments.prompt(prompt)
    if is_discovered_harness(agent):
        raise feature_unavailable("harness")
    if agent.method in ("zip_runtime", "studio", "byoc", "harness", DISCOVERED_METHOD):
        # A2A-protocol runtimes speak JSON-RPC; the A2A server owns conversation
        # state and is never A/B-routed. N16-obs79: the memory actor rides as message
        # metadata so the A2A template keys its memory on the same ``<agent>__<human>``
        # actor the HTTP envelope carries (and the console reads back).
        if (agent.spec or {}).get("protocol") == "a2a":
            files = (
                {"attachments": attachments.native} if attachments and attachments.native else {}
            )
            # stream A2: the token's ``sid`` must be the session the Runtime sees; with the
            # carrier on that is this principal's own runtime session of the conversation
            # (re-review defect 2), and the caller keeps its own session id
            runtime_session = session_id
            if principal_mint.carrier_on(agent):
                session_id = session_id or rt.new_session_id()
                runtime_session = principal_mint.runtime_session_id(agent, principal, session_id)
                token = principal_mint.mint_for_turn(
                    agent, principal, session_id=runtime_session,
                    channel=_token_channel(principal, token_channel))
                if token:
                    files["principal_token"] = token
            with principal_mint.session_turn(agent, runtime_session or ""):
                result = rt.invoke_a2a_text(
                    data_client(workspace), agent.arn, prompt, session_id=runtime_session,
                    runtime_user_id=_runtime_user_id(agent, actor_id, runtime_user_id),
                    actor_id=actor_id,
                    # N16-obs90: signed with the per-agent key (a transient row without an
                    # id, tests only, sends no actor metadata — the template would refuse it)
                    actor_key=a2a_actor.actor_key(agent.id) if agent.id else None,
                    **files,
                )
            if runtime_session != session_id:
                result = {**result, "session_id": session_id}
            return result
        resolved_user = _runtime_user_id(agent, actor_id, runtime_user_id)
        # resolved BEFORE dispatch: the A/B / canary arm is sticky on the session id
        session_id = session_id or rt.new_session_id()
        kwargs: dict[str, Any] = {
            "session_id": session_id,
            "actor_id": actor_id,
            "runtime_user_id": resolved_user,
        }
        if attachments and attachments.native:
            kwargs["attachments"] = attachments.native
        force_reauth = _pending_force_reauth(agent, resolved_user)
        if force_reauth:
            kwargs["force_reauth_providers"] = force_reauth
        kwargs.update(_routing_kwargs(agent, session_id))
        # re-review defect 2: with the carrier on, this principal's own runtime session of
        # the conversation (the caller's id unchanged with it off)
        runtime_session = principal_mint.runtime_session_id(agent, principal, session_id)
        kwargs["session_id"] = runtime_session
        _with_principal(kwargs, principal_mint.mint_for_turn(
            agent, principal, session_id=runtime_session,
            channel=_token_channel(principal, token_channel)))
        try:
            with principal_mint.session_turn(agent, runtime_session):
                result = rt.invoke_runtime_text(
                    data_client(workspace), agent.arn, prompt, **kwargs
                )
        except rt.SdkStreamError as exc:
            # N17-obs95: the SDK's terminal error frame on a sync entrance is an envelope
            raise runtime_stream_error(exc) from exc
        if runtime_session != session_id:
            result["session_id"] = session_id  # the caller continues under its own id
        if result.get("auth_required"):
            result["auth_required"] = _record_auth_sessions(
                agent, resolved_user, result["auth_required"], console_user=console_user,
            )
        if result.get("policy_decisions"):
            # D20 P2-a: the runtime guard's decisions this turn, audited here (source
            # `runtime`, channel per entry point) — `policy_denied` carries the refused ones
            result["policy_decisions"] = [
                _audit_runtime_decision(agent, principal, data, session_id=session_id)
                for data in result["policy_decisions"]
            ]
            denied = [d for d in result["policy_decisions"] if d.get("decision") == "deny"]
            if denied:
                result["policy_denied"] = denied
        # N17-obs507: Gateway denials read out of the tool results (the sync twin of the
        # stream's derived frame) — `/v1` sees the same `policy_denied` list as Chat
        already = {str(d.get("tool") or "") for d in result.get("policy_denied") or []}
        derived = []
        for data in result.pop("tool_results", None) or []:
            frame = _gateway_denial(agent, principal, data, session_id)
            if frame is not None and frame["tool"] not in already:
                already.add(frame["tool"])
                derived.append(frame)
        if derived:
            result["policy_denied"] = [*(result.get("policy_denied") or []), *derived]
        return result
    raise AppError(
        "agent.method_not_available",
        f"no invoke path for method '{agent.method}'",
        status_code=400,
    )


def stop_agent_session(
    agent: Agent,
    session_id: str,
    workspace: WorkspaceContext | None = None,
) -> dict[str, Any]:
    """End one live AgentCore Runtime session behind a conversation.

    Same method dispatch and data-plane client as the invoke path, so Chat ends the
    very session it talked to. AWS answering `ResourceNotFoundException` means the
    session already ended (explicitly, or by idle expiry) — reported as success
    with ``already_ended`` rather than as an error, because the caller's goal is
    reached either way. Any other `ClientError` propagates to the shared envelope
    mapping (a `RetryableConflictException` that outlived botocore's retries → 409).
    """
    if is_discovered_harness(agent):
        raise AppError(
            "chat.session_stop_unsupported",
            "the managed Harness service has no session-stop operation; "
            "start a new session instead",
            {"reason_code": "harness", "method": agent.method},
            status_code=409,
        )
    if agent.method not in RUNTIME_SESSION_METHODS or not agent.arn:
        raise AppError(
            "chat.session_stop_unsupported",
            f"no AgentCore Runtime session to stop for method '{agent.method}'",
            {"reason_code": "no-runtime", "method": agent.method},
            status_code=409,
        )
    workspace = _agent_workspace(agent, workspace)
    # re-review defect 2: with the carrier on, each principal of the conversation ran in its
    # own derived runtime session — ending the conversation ends every one of them
    targets = [session_id]
    if principal_mint.carrier_on(agent):
        targets += [s for s in principal_mint.runtime_sessions_for(agent.id, session_id)
                    if s != session_id]
    already = 0
    for target in targets:
        try:
            rt.stop_runtime_session(
                data_client(workspace), runtime_arn=agent.arn, session_id=target
            )
        except ClientError as exc:
            if aws_error_code(exc) != "ResourceNotFoundException":
                raise
            already += 1
    return {"ended": True, "already_ended": already == len(targets)}


def invoke_agent_events(
    agent: Agent,
    prompt: str,
    session_id: str | None = None,
    actor_id: str = "default",
    runtime_user_id: str | None = None,
    workspace: WorkspaceContext | None = None,
    attachments: PreparedAttachments | None = None,
    console_user: bool = True,
    principal: Principal | None = None,
    token_channel: str | None = None,
) -> Iterator[dict[str, Any]]:
    """Yield native runtime events, with a buffered compatibility fallback.

    Claude SDK containers and generated Strands zip runtimes both emit the
    delta/tool/complete envelope over the Runtime SSE response, so they are
    parsed incrementally. A zip runtime deployed before its template streamed
    still answers a JSON ``{"result": ...}`` body, which the same parser turns
    into one delta — so the switch is safe for existing agents.
    ``console_user`` and ``principal`` as on ``invoke_agent_text`` (the principal only
    names whose token the turn carries; nothing gates the invoke itself).
    """
    require_invoke_capability(agent)
    refuse_reserved_session_id(session_id)
    refuse_assistant_session(agent, session_id)
    require_session_open(agent, session_id)
    workspace = _agent_workspace(agent, workspace)
    streams_natively = (
        agent.method in NATIVE_STREAM_METHODS
        and (agent.spec or {}).get("protocol", "http") != "a2a"
    )
    if streams_natively:
        resolved_user = _runtime_user_id(agent, actor_id, runtime_user_id)
        session_id = session_id or rt.new_session_id()
        kwargs: dict[str, Any] = {
            "session_id": session_id,
            "actor_id": actor_id,
            "runtime_user_id": resolved_user,
        }
        if attachments:
            prompt = attachments.prompt(prompt)
            if attachments.native:
                kwargs["attachments"] = attachments.native
        force_reauth = _pending_force_reauth(agent, resolved_user)
        if force_reauth:
            kwargs["force_reauth_providers"] = force_reauth
        # same sticky arm as the synchronous entrance; streaming is never downgraded
        # for a routed session (the Global build buffered canary traffic)
        kwargs.update(_routing_kwargs(agent, session_id))
        runtime_session = principal_mint.runtime_session_id(agent, principal, session_id)
        kwargs["session_id"] = runtime_session
        _with_principal(kwargs, principal_mint.mint_for_turn(
            agent, principal, session_id=runtime_session,
            channel=_token_channel(principal, token_channel)))
        # N17-obs507: tools the stream already said were policy-denied (a frame the runtime
        # emitted itself) — a denial derived from the tool result is not emitted twice
        denied_tools: set[str] = set()
        with principal_mint.session_turn(agent, runtime_session):
            for event in rt.stream_runtime_events(
                data_client(workspace), agent.arn, prompt, **kwargs
            ):
                if event.get("event") == "auth_required":
                    event = {
                        "event": "auth_required",
                        "data": _record_auth_sessions(
                            agent, resolved_user, [event["data"]], console_user=console_user,
                        )[0],
                    }
                elif event.get("event") in policy_enforcement.RUNTIME_DECISION_EVENTS:
                    # D20 P2-a: one audit row per guard decision, its id onto the frame the
                    # console's PolicyDenyCard links to the Decisions tab
                    event = {
                        "event": event["event"],
                        "data": _audit_runtime_decision(
                            agent, principal, event["data"], session_id=session_id,
                        ),
                    }
                    denied_tools.add(str(event["data"].get("tool") or ""))
                yield event
                if event.get("event") == "tool_result":
                    # N17-obs507 (Global parity): the Gateway interceptor's denial arrives as
                    # the tool's result text — the `policy_denied` frame (the console's
                    # Chinese deny card, the `policy` history row) is derived right after it
                    denied = _gateway_denial(agent, principal, event["data"], session_id)
                    if denied is not None and denied["tool"] not in denied_tools:
                        denied_tools.add(denied["tool"])
                        yield {"event": "policy_denied", "data": denied}
        return

    extra: dict[str, Any] = {"attachments": attachments} if attachments else {}
    if not console_user:
        extra["console_user"] = False
    if principal is not None:
        extra["principal"] = principal
    if token_channel:
        extra["token_channel"] = token_channel
    result = invoke_agent_text(
        agent,
        prompt,
        session_id=session_id,
        actor_id=actor_id,
        runtime_user_id=runtime_user_id,
        workspace=workspace,
        **extra,
    )
    for ask in result.get("auth_required") or []:
        yield {"event": "auth_required", "data": ask}
    text = result["text"]
    for index in range(0, len(text), BUFFERED_CHUNK_CHARS):
        yield {
            "event": "delta",
            "data": {"text": text[index : index + BUFFERED_CHUNK_CHARS]},
        }
    if result.get("truncated"):
        # N-SCN-bug4: the buffered path forwards the max_tokens marker the same way the
        # native stream does, so the console's inline notice does not depend on the method
        yield {
            "event": "truncated",
            "data": {"truncated": True, "stop_reason": "max_tokens", "continuations": 0},
        }
