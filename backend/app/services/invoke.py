RESERVED_SESSION_PREFIX = principal_mint.RUNTIME_SESSION_PREFIX


def validate_session_id(session_id: str | None) -> None:
    """N-SCN-obs16: a caller-supplied ``session_id`` must satisfy the AgentCore Runtime
    ``runtimeSessionId`` bounds (``rt.SESSION_ID_MIN_LEN``–``rt.SESSION_ID_MAX_LEN`` = 33–100
    characters) and the routers check it FIRST — before the policy gate records a decision
    and before any AWS call — instead of letting the data plane fail the turn with
    ``ParamValidationError`` after the audit row exists. N16-obs72: the character class is
    checked too (``rt.SESSION_ID_PATTERN``: ASCII letters / digits / ``-`` / ``_``, leading
    alphanumeric) — a CJK or blank-bearing id used to pass here and die at AWS as a signature
    mismatch. ``None`` / empty passes: a fresh session's id is generated by
    ``rt.new_session_id`` (64 chars) and never checked here.
    Raises 422 ``chat.session_id_invalid`` naming the rule."""
    if not session_id:
        return
    validate_session_id_syntax(session_id)
    refuse_reserved_session_id(session_id)
    length = len(session_id)
    if length < rt.SESSION_ID_MIN_LEN or length > rt.SESSION_ID_MAX_LEN:
        raise AppError(
            "chat.session_id_invalid",
            f"session_id must be {rt.SESSION_ID_MIN_LEN}–{rt.SESSION_ID_MAX_LEN} characters "
            f"(AgentCore runtimeSessionId); got {length} — omit it to start a new session",
            {"length": length, "min_length": rt.SESSION_ID_MIN_LEN,
             "max_length": rt.SESSION_ID_MAX_LEN},
            status_code=422,
        )


def refuse_reserved_session_id(session_id: str | None) -> None:
    """Per-user policy: ``lpp-`` names the per-principal runtime sessions the hub derives
    (``principal_mint.runtime_session_id``) — a caller may not choose one, or it could land
    in another principal's runtime process. 422 ``chat.session_id_reserved`` on every
    entrance (Chat, the console invoke, ``/v1``, the A2A branch), switch on OR off."""
    if session_id and session_id[:len(RESERVED_SESSION_PREFIX)].lower() == \
            RESERVED_SESSION_PREFIX:
        raise AppError(
            "chat.session_id_reserved",
            f"session ids starting with {RESERVED_SESSION_PREFIX!r} are reserved by the "
            "platform — omit session_id to start a new session",
            {"prefix": RESERVED_SESSION_PREFIX}, status_code=422,
        )


def validate_session_id_syntax(session_id: str) -> None:
    """The character-class half of ``validate_session_id`` (N16-obs72), on its own for the
    by-id chat routes (history / memory / stop / reattach): an id that could never name a
    runtime session is 422 ``chat.session_id_invalid`` before the ledger is consulted, while
    a well-formed unknown id stays the route's 404 — the two are not confusable. Length is
    not checked here: those routes answer for ledger rows, whose ids predate the bounds."""
    if not rt.SESSION_ID_RE.fullmatch(session_id):
        raise AppError(
            "chat.session_id_invalid",
            f"session_id must match {rt.SESSION_ID_PATTERN} (ASCII letters, digits, '-' and "
            f"'_'; AgentCore runtimeSessionId) — omit it to start a new session",
            {"length": len(session_id), "min_length": rt.SESSION_ID_MIN_LEN,
             "max_length": rt.SESSION_ID_MAX_LEN, "pattern": rt.SESSION_ID_PATTERN},
            status_code=422,
        )


