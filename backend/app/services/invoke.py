def require_session_open(agent: Agent, session_id: str | None) -> None:
    """N16-obs88: a turn under an ENDED chat session id is ``409 chat.session_ended
    {session_id, ended_at}`` on EVERY entrance — here, in the one chain the console and
    ``/v1`` share, before the policy gate and any AWS call — exactly as the console route
    answers since N16-obs79. A missing id (a new session) or an id with no ledger row
    passes; the ledger row is never touched by the refusal."""
    if session_id:
        chat_ledger.require_session_open(agent.workspace_id or "", agent.id, session_id)


