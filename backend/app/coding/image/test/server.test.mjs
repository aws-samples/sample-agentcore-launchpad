import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { after, before, describe, test } from "node:test";

import { RESTORE_SEQ_GAP, createHttpServer } from "../src/server.mjs";
import {
  call, cleanup, makeLayout, makeRuntime, methods, ok, siblingLayout, startBlobServer, waitForEvent,
} from "./helpers.mjs";

const STEP = { totalTokens: 175, inputTokens: 100, cachedInputTokens: 40, cacheWriteInputTokens: 10,
  outputTokens: 20, reasoningOutputTokens: 5 };
const times = (n) => Object.fromEntries(Object.entries(STEP).map(([k, v]) => [k, v * n]));

const finished = (rt, turnId) => waitForEvent(rt, "launchpad/turnUsage", (r) => r.params.turnId === turnId);

describe("a turn end to end", () => {
  let lay;
  let rt;
  before(async () => { lay = await makeLayout(); rt = makeRuntime(lay); });
  after(async () => { await cleanup(rt, lay?.root); });

  test("the first invocation initializes the workspace", async () => {
    const status = await ok(rt, "status");
    assert.equal(status.busy, false);
    assert.equal(status.active_turn, null);
    assert.equal(status.thread_id, null);
    assert.equal(status.restored, false);
    assert.ok(fs.existsSync(path.join(lay.workspace, ".launchpad", "initialized")));
    assert.ok(fs.existsSync(path.join(lay.workspace, "project", "AGENTS.md")));
    assert.deepEqual(rt.ping().status, "Healthy");
  });

  test("streams deltas, completes, and emits launchpad/turnUsage", async () => {
    // the live log, before turn-end compaction drops the completed item's deltas
    const live = [];
    const onNotification = rt.onNotification.bind(rt);
    rt.onNotification = (method, params) => { live.push(method); onNotification(method, params); };
    const started = await ok(rt, "start_turn", { prompt: "say hello", model: "model-a", effort: "high" });
    assert.match(started.turn_id, /^turn_/);
    assert.match(started.thread_id, /^thr_/);
    const usage = await finished(rt, started.turn_id);
    rt.onNotification = onNotification;
    assert.equal(live.filter((m) => m === "item/agentMessage/delta").length, 3, "deltas streamed live");
    const all = methods(rt.eventLog.records);
    for (const m of ["thread/started", "turn/started", "item/completed",
      "turn/diff/updated", "thread/tokenUsage/updated", "turn/completed", "launchpad/turnUsage"]) {
      assert.ok(all.includes(m), `log has ${m}`);
    }
    assert.equal(all.indexOf("launchpad/turnUsage"), all.lastIndexOf("turn/completed") + 1,
      "turnUsage lands right after turn/completed");
    assert.deepEqual(usage.params.usage, times(2), "two model calls summed");
    assert.equal(usage.params.model, "model-a");
    assert.equal(usage.params.effort, "high");
    assert.equal(usage.params.status, "completed");
    assert.equal(rt.busy, 0);
    assert.equal(rt.ping().status, "Healthy");
    const status = await ok(rt, "status");
    assert.equal(status.thread_id, started.thread_id);
    assert.equal(status.last_turn.turn_id, started.turn_id);
    assert.equal(status.last_turn.status, "completed");
  });

  test("the log is compacted at turn end; seqs survive", async () => {
    const page = await ok(rt, "events", { after: 0, limit: 2000 });
    assert.ok(!methods(page.events).includes("item/agentMessage/delta"), "deltas of the completed item dropped");
    assert.ok(!methods(page.events).includes("account/rateLimits/updated"));
    assert.equal(page.events.filter((e) => e.method === "turn/diff/updated").length, 1);
    assert.equal(page.seq, rt.eventLog.seq);
    const onDisk = fs.readFileSync(rt.paths.eventsFile, "utf8").trim().split("\n").map((l) => JSON.parse(l));
    assert.deepEqual(onDisk.map((r) => r.seq), page.events.map((e) => e.seq));
  });

  test("a second turn continues the thread and is charged only its own usage", async () => {
    const before = (await ok(rt, "status")).thread_id;
    const started = await ok(rt, "start_turn", { prompt: "write-file please", model: "model-b" });
    assert.equal(started.thread_id, before);
    const usage = await finished(rt, started.turn_id);
    assert.deepEqual(usage.params.usage, times(2));
    assert.equal(usage.params.effort, "medium", "effort defaults to medium");
    const changes = await ok(rt, "changes", { scope: "turn" });
    assert.deepEqual(changes.changes, [{ path: "generated.txt", status: "A" }]);
    const atTurnStart = await ok(rt, "read_file", { path: "generated.txt", rev: "turn" });
    assert.equal(atTurnStart.exists, false);
    const now = await ok(rt, "read_file", { path: "generated.txt" });
    assert.match(now.content, /generated by/);
    const diff = await ok(rt, "diff", { scope: "turn" });
    assert.match(diff.diff, /generated\.txt/);
  });

  test("the app-server was spawned with local-disk sqlite and the region override", () => {
    const first = JSON.parse(fs.readFileSync(lay.log, "utf8").split("\n")[0]);
    assert.ok(first.argv.includes(`sqlite_home=${JSON.stringify(lay.stateDir)}`));
    assert.ok(first.argv.includes('model_providers.amazon-bedrock-runtime.aws.region="us-west-2"'));
    assert.equal(first.codexHome, path.join(lay.workspace, ".codex"));
  });

  test("JSON-RPC framing: requests carry id+method, no jsonrpc field; initialized follows initialize", () => {
    const lines = fs.readFileSync(lay.log, "utf8").trim().split("\n").slice(1).map((l) => JSON.parse(l));
    assert.equal(lines[0].method, "initialize");
    assert.equal(typeof lines[0].id, "number");
    assert.equal(lines[1].method, "initialized");
    assert.equal(lines[1].id, undefined);
    for (const msg of lines) assert.equal(msg.jsonrpc, undefined);
    const turnStart = lines.find((m) => m.method === "turn/start");
    assert.equal(turnStart.params.summary, "auto");
    assert.deepEqual(turnStart.params.input, [{ type: "text", text: "say hello", text_elements: [] }]);
    const threadStart = lines.find((m) => m.method === "thread/start");
    assert.equal(threadStart.params.approvalPolicy, "never");
    assert.equal(threadStart.params.sandbox, "danger-full-access");
  });
});

describe("one turn at a time, interrupts, long-polls", () => {
  let lay;
  let rt;
  before(async () => { lay = await makeLayout(); rt = makeRuntime(lay); await ok(rt, "status"); });
  after(async () => { await cleanup(rt, lay?.root); });

  test("a running turn keeps /ping busy and refuses a second turn and writes", async () => {
    const started = await ok(rt, "start_turn", { prompt: "slow job", model: "model-a" });
    assert.equal(rt.ping().status, "HealthyBusy");
    const again = await call(rt, "start_turn", { prompt: "another", model: "model-a" });
    assert.equal(again.ok, false);
    assert.equal(again.error.code, "turn_running");
    const write = await call(rt, "write_file", { path: "x.txt", content: "x" });
    assert.equal(write.error.code, "turn_running");
    const status = await ok(rt, "status");
    assert.equal(status.busy, true);
    assert.equal(status.active_turn.turn_id, started.turn_id);
    // reads keep working during the turn (concurrent invokes on one session)
    assert.equal((await ok(rt, "read_file", { path: "AGENTS.md" })).exists, true);
    await waitForEvent(rt, "item/commandExecution/outputDelta");
  });

  test("a long-poll wakes on new events, live reads keep deltas", async () => {
    const cursor = rt.eventLog.seq;
    const t0 = Date.now();
    const page = await ok(rt, "events", { after: cursor, wait_ms: 5000 });
    assert.ok(Date.now() - t0 < 2000, "woken by the next output delta");
    assert.ok(page.events.length >= 1);
    assert.ok(page.events.every((e) => e.seq > cursor));
    assert.equal(page.events[0].method, "item/commandExecution/outputDelta");
    assert.ok(page.active_turn);
    assert.equal(page.boot_id, rt.bootId);
  });

  test("interrupt stops the turn and a new one is accepted", async () => {
    const active = rt.activeTurn.turnId;
    const out = await ok(rt, "interrupt");
    assert.deepEqual(out, { interrupted: true, turn_id: active });
    const usage = await finished(rt, active);
    assert.equal(usage.params.status, "interrupted");
    assert.equal(rt.ping().status, "Healthy");
    assert.deepEqual(await ok(rt, "interrupt"), { interrupted: false });
    const next = await ok(rt, "start_turn", { prompt: "quick", model: "model-a" });
    await finished(rt, next.turn_id);
  });

  test("an empty long-poll returns after wait_ms", async () => {
    const t0 = Date.now();
    const page = await ok(rt, "events", { after: rt.eventLog.seq, wait_ms: 80 });
    assert.deepEqual(page.events, []);
    assert.ok(Date.now() - t0 >= 70);
    assert.equal((await ok(rt, "events", { after: rt.eventLog.seq + 10 })).cursor_ahead, true);
  });

  test("server->client requests are declined and logged (full-auto)", async () => {
    const started = await ok(rt, "start_turn", { prompt: "approval needed", model: "model-a" });
    const answered = await waitForEvent(rt, "fake/serverRequestAnswered");
    assert.equal(answered.params.result, null);
    assert.equal(answered.params.error.code, -32601);
    const declined = await waitForEvent(rt, "launchpad/serverRequestDeclined");
    assert.equal(declined.params.method, "item/commandExecution/requestApproval");
    await finished(rt, started.turn_id);
  });

  test("a turn/completed that beats the turn/start answer still closes the turn", async () => {
    const started = await ok(rt, "start_turn", { prompt: "early finish", model: "model-a" });
    await finished(rt, started.turn_id);
    assert.equal(rt.activeTurn, null);
    assert.equal(rt.busy, 0);
  });

  test("input validation", async () => {
    const cases = [
      [{ prompt: "", model: "model-a" }, "bad_request"],
      [{ prompt: "x", model: "not-enabled" }, "bad_request"],
      [{ prompt: "x", model: "model-a", effort: "ludicrous" }, "bad_request"],
      [{ prompt: "x".repeat(32 * 1024 + 1), model: "model-a" }, "bad_request"],
    ];
    for (const [payload, code] of cases) {
      const out = await call(rt, "start_turn", payload);
      assert.equal(out.ok, false);
      assert.equal(out.error.code, code, JSON.stringify(payload).slice(0, 80));
    }
    assert.equal((await call(rt, "no_such_action")).error.code, "bad_request");
    assert.equal((await call(rt, "constructor")).error.code, "bad_request", "no prototype lookups");
    assert.equal((await call(rt, "read_file", { path: "../etc/passwd" })).error.code, "path_invalid");
    assert.equal((await call(rt, "read_file", { path: "AGENTS.md", rev: "HEAD~1" })).error.code, "bad_request");
  });

  test("a write with a stale hash answers conflict with the current hash", async () => {
    const first = await ok(rt, "write_file", { path: "edit.md", content: "one\n" });
    await ok(rt, "write_file", { path: "edit.md", content: "two\n" });
    const stale = await call(rt, "write_file", { path: "edit.md", content: "mine\n", expected_sha256: first.sha256 });
    assert.equal(stale.ok, false);
    assert.equal(stale.error.code, "conflict");
    assert.equal(stale.error.sha256, (await ok(rt, "read_file", { path: "edit.md" })).sha256);
  });
});

describe("crashes and reboots", () => {
  let lay;
  let rt;
  let rt2;
  before(async () => { lay = await makeLayout(); rt = makeRuntime(lay); await ok(rt, "status"); });
  after(async () => { await cleanup(rt, rt2, lay?.root); });

  test("an app-server crash mid-turn abandons the turn and clears busy", async () => {
    const started = await ok(rt, "start_turn", { prompt: "crash now", model: "model-a" });
    const abandoned = await waitForEvent(rt, "launchpad/turnAbandoned");
    assert.equal(abandoned.params.turnId, started.turn_id);
    assert.equal(abandoned.params.reason, "app_server_exited");
    assert.ok(methods(rt.eventLog.records).includes("launchpad/appServerExited"));
    assert.equal(rt.busy, 0);
    // the next turn respawns the app-server and resumes the same thread
    const next = await ok(rt, "start_turn", { prompt: "carry on", model: "model-a" });
    assert.equal(next.thread_id, started.thread_id);
    await finished(rt, next.turn_id);
  });

  test("a new microVM over the same storage abandons the dead VM's turn", async () => {
    const started = await ok(rt, "start_turn", { prompt: "slow again", model: "model-a" });
    await waitForEvent(rt, "item/commandExecution/outputDelta", (r) => r.params.turnId === started.turn_id);
    rt.eventLog.flushSync();
    const lastSeqOnDisk = rt.eventLog.seq;
    // the microVM dies without a word: nothing it does from here reaches the storage
    rt.app.opts.onNotification = () => {};
    rt.app.opts.onExit = () => {};
    rt.eventLog.append = () => ({});
    rt.eventLog.flushSync = () => {};
    rt.ws.writeState = () => {};
    await cleanup(rt);
    rt = null;
    // a new process mounts the same session storage
    rt2 = makeRuntime(lay);
    const status = await ok(rt2, "status");
    assert.equal(status.active_turn, null);
    assert.equal(status.last_turn.status, "abandoned");
    const abandoned = rt2.eventLog.records.filter((r) => r.method === "launchpad/turnAbandoned").at(-1);
    assert.equal(abandoned.params.turnId, started.turn_id);
    assert.equal(abandoned.params.reason, "runtime_restarted");
    assert.equal(abandoned.seq, lastSeqOnDisk + 1, "seq continues on the shared log");
  });

  test("a thread whose rollout is gone continues in a new thread", async () => {
    const state = rt2.ws.readState();
    rt2.ws.writeState({ ...state, threadId: "missing-thread" });
    const started = await ok(rt2, "start_turn", { prompt: "go on", model: "model-a" });
    assert.notEqual(started.thread_id, "missing-thread");
    const failed = await waitForEvent(rt2, "launchpad/threadResumeFailed");
    assert.equal(failed.params.threadId, "missing-thread");
    await finished(rt2, started.turn_id);
    assert.equal(rt2.ws.readState().threadId, started.thread_id);
  });
});

describe("a wiped workspace without a snapshot", () => {
  let lay;
  let lay2;
  let rt;
  let rt2;
  before(async () => { lay = await makeLayout(); rt = makeRuntime(lay); });
  after(async () => { await cleanup(rt, rt2, lay?.root, lay2?.root); });

  test("a fresh log starts above every seq the wiped log issued", async () => {
    const before = Date.now() * 1000;
    const started = await ok(rt, "start_turn", { prompt: "write-file", model: "model-a" });
    await finished(rt, started.turn_id);
    const oldSeq = rt.eventLog.seq;
    assert.ok(oldSeq >= before, "a brand-new project's log starts at a time-based seq");

    // a version update before any snapshot: fresh microVM, empty session storage
    lay2 = await siblingLayout(lay);
    rt2 = makeRuntime(lay2);
    const status = await ok(rt2, "status");
    assert.equal(status.restored, false);
    assert.ok(rt2.eventLog.seq > oldSeq, "the fresh log's counter starts above the wiped log");
    const again = await ok(rt2, "start_turn", { prompt: "write-file", model: "model-a" });
    await finished(rt2, again.turn_id);
    const page = await ok(rt2, "events", { after: oldSeq, wait_ms: 0 });
    assert.ok(page.events.length > 0, "a reader holding the old cursor still sees the new log");
    assert.ok(page.events.every((e) => e.seq > oldSeq));
  });
});

describe("restore from a snapshot", () => {
  let lay;
  let lay2;
  let rt;
  let rt2;
  let blobs;
  before(async () => {
    blobs = await startBlobServer();
    lay = await makeLayout();
    rt = makeRuntime(lay);
  });
  after(async () => { await cleanup(rt, rt2, blobs, lay?.root, lay2?.root); });

  test("a wiped workspace restores once, before the action runs", async () => {
    const started = await ok(rt, "start_turn", { prompt: "write-file", model: "model-a" });
    await finished(rt, started.turn_id);
    await ok(rt, "write_file", { path: "manual.md", content: "saved by the user\n" });
    const snap = await ok(rt, "snapshot", { put_url: blobs.url("snap.tgz") });
    assert.ok(snap.bytes > 0 && snap.files > 0);
    const seqAtSnapshot = rt.eventLog.seq;

    // a runtime version update: fresh microVM, empty session storage
    lay2 = await siblingLayout(lay);
    rt2 = makeRuntime(lay2);
    const restoreUrl = blobs.url("snap.tgz");
    const results = await Promise.all([
      call(rt2, "status", { restore_url: restoreUrl }),
      call(rt2, "read_file", { path: "manual.md", restore_url: restoreUrl }),
      call(rt2, "tree", { restore_url: restoreUrl }),
    ]);
    for (const r of results) assert.equal(r.ok, true, JSON.stringify(r.error));
    assert.equal(blobs.counts.get, 1, "single-flight: one download for concurrent first calls");
    assert.equal(results[0].result.restored, true);
    assert.equal(results[1].result.content, "saved by the user\n", "the action saw restored files");
    assert.equal(results[0].result.thread_id, started.thread_id);
    const restored = rt2.eventLog.records.find((r) => r.method === "launchpad/restored");
    assert.ok(restored.seq > seqAtSnapshot + RESTORE_SEQ_GAP - 1, "seq jumps past anything issued after the snapshot");
    assert.ok((fs.lstatSync(path.join(lay2.workspace, "project", "node_modules"))).isSymbolicLink());

    // initialized now: a later restore_url is ignored
    await ok(rt2, "status", { restore_url: restoreUrl });
    assert.equal(blobs.counts.get, 1);
    const next = await ok(rt2, "start_turn", { prompt: "continue", model: "model-a" });
    assert.equal(next.thread_id, started.thread_id, "the conversation continues on the restored thread");
    await finished(rt2, next.turn_id);
  });

  test("a failed restore is retried by the next call", async () => {
    const lay3 = await siblingLayout(lay);
    const rt3 = makeRuntime(lay3);
    try {
      const bad = await call(rt3, "status", { restore_url: blobs.url("missing.tgz") });
      assert.equal(bad.ok, false);
      assert.equal(bad.error.code, "restore_failed");
      assert.equal(rt3.busy, 0);
      const good = await call(rt3, "status", { restore_url: blobs.url("snap.tgz") });
      assert.equal(good.ok, true);
      assert.equal(good.result.restored, true);
    } finally {
      await cleanup(rt3, lay3.root);
    }
  });

  test("export hands over a zip; an export or snapshot without a URL is refused", async () => {
    const out = await ok(rt2, "export", { put_url: blobs.url("export.zip") });
    assert.ok(out.files > 0 && out.root_files.includes("manual.md"));
    assert.equal((await call(rt2, "export", {})).error.code, "bad_request");
    assert.equal((await call(rt2, "snapshot", {})).error.code, "bad_request");
  });
});

describe("HTTP contract", () => {
  let lay;
  let rt;
  let server;
  let base;
  before(async () => {
    lay = await makeLayout();
    rt = makeRuntime(lay);
    server = createHttpServer(rt);
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    base = `http://127.0.0.1:${server.address().port}`;
  });
  after(async () => {
    server.closeAllConnections?.();
    await new Promise((resolve) => server.close(resolve));
    await cleanup(rt, lay?.root);
  });

  test("GET /ping answers the AgentCore health shape", async () => {
    const res = await fetch(`${base}/ping`);
    assert.equal(res.status, 200);
    const body = await res.json();
    assert.equal(body.status, "Healthy");
    assert.equal(typeof body.time_of_last_update, "number");
  });

  test("POST /invocations always answers HTTP 200 with the envelope", async () => {
    const good = await fetch(`${base}/invocations`, { method: "POST", body: JSON.stringify({ action: "status" }) });
    assert.equal(good.status, 200);
    const body = await good.json();
    assert.equal(body.ok, true);
    assert.equal(body.action, "status");
    assert.equal(body.boot_id, rt.bootId);
    const bad = await fetch(`${base}/invocations`, { method: "POST", body: "{not json" });
    assert.equal(bad.status, 200);
    assert.deepEqual((await bad.json()).error.code, "bad_request");
    const unknown = await (await fetch(`${base}/invocations`, { method: "POST", body: "{\"action\":\"rm\"}" })).json();
    assert.equal(unknown.ok, false);
    assert.equal(unknown.error.code, "bad_request");
    assert.equal((await fetch(`${base}/nope`)).status, 404);
  });

  test("busy flips time_of_last_update", async () => {
    const t0 = (await (await fetch(`${base}/ping`)).json()).time_of_last_update;
    rt.statusChangedAt -= 5; // make a change observable within one second
    const before = rt.statusChangedAt;
    rt.setBusy(+1);
    const busy = await (await fetch(`${base}/ping`)).json();
    assert.equal(busy.status, "HealthyBusy");
    assert.ok(busy.time_of_last_update >= before);
    rt.setBusy(+1);
    assert.equal(rt.statusChangedAt, busy.time_of_last_update, "no change while still busy");
    rt.setBusy(-2);
    assert.equal((await (await fetch(`${base}/ping`)).json()).status, "Healthy");
    assert.ok(t0 > 0);
  });
});
