// A stand-in for `codex app-server` speaking the same stdio framing (newline JSON,
// {id, method, params} requests without a "jsonrpc" field, {id, result|error}
// responses, {method, params} notifications). The prompt text scripts the turn:
//
//   (default)    two model calls, an agent message in 3 deltas, a turn diff, done
//   write-file   also writes generated.txt into the cwd (an agent edit)
//   slow         streams command output every 30 ms until turn/interrupt
//   approval     asks the client for a command approval first, then finishes
//   crash        exits the process mid-turn
//   early        sends turn/completed before answering turn/start
//
// FAKE_APP_SERVER_LOG (optional) receives argv and every line read from stdin.
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";

const LOG = process.env.FAKE_APP_SERVER_LOG;
const record = (line) => { if (LOG) fs.appendFileSync(LOG, `${line}\n`); };
record(JSON.stringify({ argv: process.argv.slice(2), codexHome: process.env.CODEX_HOME || null }));

const STEP = { totalTokens: 175, inputTokens: 100, cachedInputTokens: 40, cacheWriteInputTokens: 10,
  outputTokens: 20, reasoningOutputTokens: 5 };

const send = (obj) => process.stdout.write(`${JSON.stringify(obj)}\n`);
const notify = (method, params) => send({ method, params });
const respond = (id, result) => send({ id, result });
const fail = (id, code, message) => send({ id, error: { code, message } });
const later = (ms) => new Promise((r) => setTimeout(r, ms));

let initialized = false;
let threadCounter = 0;
let turnCounter = 0;
const totals = new Map(); // threadId -> TokenUsageBreakdown
let slowTurn = null; // { threadId, turnId, timer }
const answers = new Map(); // server request id -> resolve

function addUsage(threadId, turnId) {
  const prev = totals.get(threadId) || Object.fromEntries(Object.keys(STEP).map((k) => [k, 0]));
  const total = Object.fromEntries(Object.keys(STEP).map((k) => [k, prev[k] + STEP[k]]));
  totals.set(threadId, total);
  notify("thread/tokenUsage/updated", { threadId, turnId, tokenUsage: { total, last: { ...STEP }, modelContextWindow: 1000000 } });
}

function completed(threadId, turnId, status = "completed") {
  notify("turn/completed", {
    threadId,
    turn: { id: turnId, items: [], status, error: null, startedAt: 1, completedAt: 2, durationMs: 1000 },
  });
}

async function runTurn(threadId, turnId, prompt) {
  await later(5);
  notify("turn/started", { threadId, turn: { id: turnId, items: [], status: "inProgress" } });
  if (prompt.includes("crash")) {
    await later(5);
    process.exit(3);
  }
  if (prompt.includes("slow")) {
    const itemId = `cmd_${turnId}`;
    notify("item/started", { threadId, turnId, item: { type: "commandExecution", id: itemId, command: "sleep 60" } });
    let n = 0;
    slowTurn = {
      threadId,
      turnId,
      timer: setInterval(() => notify("item/commandExecution/outputDelta", { threadId, turnId, itemId, delta: `line ${n++}\n` }), 30),
    };
    return;
  }
  if (prompt.includes("approval")) {
    const id = 9000 + turnCounter;
    const answer = new Promise((resolve) => answers.set(id, resolve));
    send({ id, method: "item/commandExecution/requestApproval", params: { threadId, turnId, itemId: "x", command: "rm -rf /" } });
    const reply = await answer;
    notify("fake/serverRequestAnswered", { id, error: reply.error ?? null, result: reply.result ?? null });
  }
  if (prompt.includes("write-file")) {
    fs.writeFileSync(path.join(process.cwd(), "generated.txt"), `generated by ${turnId}\n`);
  }
  addUsage(threadId, turnId);
  const itemId = `msg_${turnId}`;
  notify("item/started", { threadId, turnId, item: { type: "agentMessage", id: itemId, text: "" } });
  for (const delta of ["Hel", "lo", " world"]) notify("item/agentMessage/delta", { threadId, turnId, itemId, delta });
  notify("item/completed", { threadId, turnId, item: { type: "agentMessage", id: itemId, text: "Hello world" } });
  notify("turn/diff/updated", { threadId, turnId, diff: "diff --git a/x b/x\n(first)\n" });
  addUsage(threadId, turnId);
  notify("turn/diff/updated", { threadId, turnId, diff: "diff --git a/x b/x\n(final)\n" });
  notify("account/rateLimits/updated", { rateLimits: {} });
  completed(threadId, turnId);
}

function handle(msg) {
  const { id, method, params = {} } = msg;
  if (method === "initialize") return respond(id, { userAgent: "fake-app-server/0" });
  if (method === "initialized") { initialized = true; return undefined; }
  if (!initialized) return fail(id, -32002, "not initialized");
  switch (method) {
    case "thread/start": {
      const threadId = `thr_${++threadCounter}`;
      respond(id, { thread: { id: threadId } });
      return notify("thread/started", { thread: { id: threadId } });
    }
    case "thread/resume":
      if (String(params.threadId).startsWith("missing")) return fail(id, -32600, `no rollout found for thread id ${params.threadId}`);
      return respond(id, { thread: { id: params.threadId } });
    case "turn/start": {
      const turnId = `turn_${++turnCounter}`;
      const prompt = params.input?.[0]?.text || "";
      if (prompt.includes("early")) {
        completed(params.threadId, turnId);
        return respond(id, { turn: { id: turnId, items: [], status: "completed" } });
      }
      respond(id, { turn: { id: turnId, items: [], status: "inProgress" } });
      runTurn(params.threadId, turnId, prompt);
      return undefined;
    }
    case "turn/interrupt":
      respond(id, {});
      if (slowTurn && slowTurn.turnId === params.turnId) {
        clearInterval(slowTurn.timer);
        const { threadId, turnId } = slowTurn;
        slowTurn = null;
        completed(threadId, turnId, "interrupted");
      }
      return undefined;
    default:
      return fail(id, -32601, `unknown method ${method}`);
  }
}

const rl = readline.createInterface({ input: process.stdin });
rl.on("line", (line) => {
  if (!line.trim()) return;
  record(line);
  const msg = JSON.parse(line);
  if (msg.id !== undefined && msg.method === undefined) {
    answers.get(msg.id)?.(msg);
    answers.delete(msg.id);
    return;
  }
  handle(msg);
});
rl.on("close", () => process.exit(0));
process.on("SIGTERM", () => process.exit(0));
